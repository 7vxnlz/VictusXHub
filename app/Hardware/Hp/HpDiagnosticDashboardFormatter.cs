    public static IReadOnlyList<HpDiagnosticDashboardSection> BuildUserSummary(HpDiagnosticUserSummaryInput input)
    {
        return
        [
            new("Device",
            [
                UserRow("Model", input.Model),
                UserRow("SKU", input.Sku),
                UserRow("BIOS", input.BiosVersion),
                UserRow("HP/Victus detection", input.HpVictusDetection),
                UserRow("Thermal policy", input.ThermalPolicy),
                UserRow("Fan count", input.FanCount)
            ]),
            new("Live status",
            [
                UserRow("CPU load", input.CpuLoad),
                UserRow("CPU temperature", input.CpuTemperature),
                UserRow("GPU temperature", input.GpuTemperature),
                UserRow("Battery / AC / charging", input.BatteryPower),
                UserRow("Refresh rate", input.RefreshRate),
                UserRow("Fan RPM", input.FanRpm)
            ]),
            new("Capabilities",
            [
                UserRow("Performance Mode", input.PerformanceMode),
                UserRow("GPU Switching", input.GpuSwitchingCapability),
                UserRow("Keyboard Lighting", input.KeyboardBacklightCapability),
                UserRow("Battery Care", input.BatteryCareCapability),
                UserRow("Fan Control", input.FanControlStatus, blocked: true),
                UserRow("Display Control", input.DisplayControlStatus)
            ])
        ];
    }

    public static string BuildSummary(HpDiagnosticDashboardInput input)
    {
        return FormatSections(BuildSections(input));
    }

    public static string BuildCompleteSummary(
        HpDiagnosticUserSummaryInput userSummary,
        HpDiagnosticDashboardInput advanced,
        string? liveEvidence) =>
        "User summary" + Environment.NewLine +
        FormatSections(BuildUserSummary(userSummary)) + Environment.NewLine + Environment.NewLine +
        "Advanced live-status evidence" + Environment.NewLine +
        (string.IsNullOrWhiteSpace(liveEvidence) ? NotAvailable : liveEvidence.Trim()) +
        Environment.NewLine + Environment.NewLine +
        "Advanced diagnostics" + Environment.NewLine +
        FormatSections(BuildSections(advanced));

    public static string FormatWriteImplementationStatus(bool? value) => value switch
    {
        true => "Implemented",
        false => "Not implemented",
        _ => NotAvailable
    };

    public static string FormatWriteAllowedStatus(bool? value) => value switch
    {
        true => "Allowed",
        false => "Blocked",
        _ => NotAvailable
    };

    public static string FormatDeviceValidatedInputLength(string? value)
    {
        return int.TryParse(value, out int length) && length is 1 or 4
            ? length + (length == 1 ? " byte reported; not approved" : " bytes reported; not approved")
            : SetFanMaxInputLengthUnset;
    }

    public static string FormatFirstWriteGateStatus(string? value)
    {
        return string.Equals(value, "GO", StringComparison.OrdinalIgnoreCase)
            ? "Blocked - unexpected GO state"
            : SetFanMaxReadinessStatus;
    }

    public static string FormatFirstWriteGateSatisfied(string? value)
    {
        return string.Equals(value, bool.TrueString, StringComparison.OrdinalIgnoreCase)
            ? "Blocked - unexpected satisfied state"
            : SetFanMaxFirstWriteGateNotSatisfied;
    }

    public static string FormatFirstWriteGateReason(string? status, string? satisfied, string? reason)
    {
        if (string.Equals(status, "GO", StringComparison.OrdinalIgnoreCase) ||
            string.Equals(satisfied, bool.TrueString, StringComparison.OrdinalIgnoreCase))
        {
            return SetFanMaxFirstWriteGateUnexpectedReportReason;
        }

        if (string.IsNullOrWhiteSpace(status) ||
            string.IsNullOrWhiteSpace(satisfied) ||
            string.IsNullOrWhiteSpace(reason))
        {
            return SetFanMaxFirstWriteGateMissingOldReportReason;
        }

        return reason;
    }

    public static string FormatExperimentalPayloadCandidate(string? value) =>
        string.Equals(value, "FourByte", StringComparison.OrdinalIgnoreCase)
            ? "FourByte - experimental only"
            : SetFanMaxExperimentalPayloadUnknown;

    public static string FormatPhysicalResponseObserved(string? candidate, string? observed, string? confirmationCount) =>
        HasRecognizedExperimentalPhysicalResponse(candidate, observed, confirmationCount)
            ? "True - observed in two manual four-byte experiments; experimental only"
            : SetFanMaxPhysicalResponseUnknown;

    public static string FormatPhysicalResponseConfirmationCount(string? candidate, string? observed, string? value) =>
        HasRecognizedExperimentalPhysicalResponse(candidate, observed, value)
            ? "2 - manual four-byte confirmation records"
            : "Unknown";

    public static string FormatReadbackReliable(string? value) =>
        string.Equals(value, bool.TrueString, StringComparison.OrdinalIgnoreCase)
            ? "False - unexpected reliable readback claim; failing closed"
            : SetFanMaxReadbackNotReliable;

    public static string FormatDeveloperExperimentAllowed(string? allowed, string? payload) =>
        HasRecognizedDeveloperExperimentAllowance(allowed, payload)
            ? SetFanMaxDeveloperExperimentAllowed
            : SetFanMaxDeveloperExperimentNotAllowed;

    public static string FormatDeveloperExperimentPayload(string? allowed, string? payload) =>
        HasRecognizedDeveloperExperimentAllowance(allowed, payload)
            ? SetFanMaxDeveloperExperimentPayload
            : SetFanMaxDeveloperExperimentPayloadUnknown;

    public static string FormatNormalControlValidated(string? value) =>
        string.Equals(value, bool.TrueString, StringComparison.OrdinalIgnoreCase)
            ? "False - unexpected normal-control validation claim; failing closed"
            : SetFanMaxNormalControlNotValidated;

    public static string FormatUserFacingControlAllowed(string? value) =>
        string.Equals(value, bool.TrueString, StringComparison.OrdinalIgnoreCase)
            ? "False - unexpected user-facing control claim; failing closed"
            : SetFanMaxUserFacingControlNotAllowed;

    private static string FormatEvidenceWriteImplemented(string? value)
    {
        return string.Equals(value, "Implemented", StringComparison.OrdinalIgnoreCase) ||
            string.Equals(value, bool.TrueString, StringComparison.OrdinalIgnoreCase)
            ? "Blocked - unexpected implemented state"
            : "False - not implemented";
    }

    private static string FormatEvidenceWriteAllowed(string? value)
    {
        return string.Equals(value, "Allowed", StringComparison.OrdinalIgnoreCase) ||
            string.Equals(value, bool.TrueString, StringComparison.OrdinalIgnoreCase)
            ? "Blocked - unexpected allowed state"
            : "False - blocked";
    }

    private static bool HasRecognizedExperimentalPhysicalResponse(string? candidate, string? observed, string? confirmationCount) =>
        string.Equals(candidate, "FourByte", StringComparison.OrdinalIgnoreCase) &&
        string.Equals(observed, bool.TrueString, StringComparison.OrdinalIgnoreCase) &&
        string.Equals(confirmationCount, "2", StringComparison.Ordinal);

    private static bool HasRecognizedDeveloperExperimentAllowance(string? allowed, string? payload) =>
        string.Equals(allowed, bool.TrueString, StringComparison.OrdinalIgnoreCase) &&
        string.Equals(payload, "FourByte", StringComparison.OrdinalIgnoreCase);

    public static string FormatReportSchemaVersion(string? value)
    {
        return int.TryParse(value, out int version) && version > 0
            ? "v" + version
            : LegacyReportSchema;
    }

    public static string FormatReportTimestamp(string? value)
    {
        return DateTimeOffset.TryParse(value, out DateTimeOffset timestamp)
            ? timestamp.ToString("yyyy-MM-dd HH:mm:ss zzz", System.Globalization.CultureInfo.InvariantCulture)
            : NotAvailable;
    }

    private static HpDiagnosticDashboardRow Row(string label, string? value, bool blocked = false)
    {
        string displayValue = string.IsNullOrWhiteSpace(value) ? NotAvailable : value;
        return new HpDiagnosticDashboardRow(
            label,
            displayValue,
            blocked ? HpDiagnosticDashboardStatus.Blocked : GetStatus(displayValue));
    }

    private static HpDiagnosticDashboardRow UserRow(string label, string? value, bool blocked = false)
    {
        string displayValue = string.IsNullOrWhiteSpace(value) ? "Unavailable" : value;
        HpDiagnosticDashboardStatus status = blocked
            ? HpDiagnosticDashboardStatus.Blocked
            : IsUnavailableUserValue(displayValue)
                ? HpDiagnosticDashboardStatus.Normal
                : HpDiagnosticDashboardStatus.Ready;
        return new HpDiagnosticDashboardRow(label, displayValue, status);
    }

    private static string FormatSections(IReadOnlyList<HpDiagnosticDashboardSection> sections) =>
        string.Join(
            Environment.NewLine + Environment.NewLine,
            sections.Select(section => section.Title + Environment.NewLine +
                string.Join(Environment.NewLine, section.Rows.Select(row => row.Label + ": " + row.Value))));

    private static bool IsUnavailableUserValue(string value) =>
        value.Contains("Unavailable", StringComparison.OrdinalIgnoreCase) ||
        value.Contains("Unknown", StringComparison.OrdinalIgnoreCase) ||
        value.Contains("Stale", StringComparison.OrdinalIgnoreCase) ||
        value.Contains("Not sampled", StringComparison.OrdinalIgnoreCase) ||
        value.Contains("not detected", StringComparison.OrdinalIgnoreCase) ||
        value.Contains("Not supported", StringComparison.OrdinalIgnoreCase) ||
        value.Contains("Not exposed", StringComparison.OrdinalIgnoreCase) ||
        value.Contains("No battery", StringComparison.OrdinalIgnoreCase) ||
        value.Contains("state unavailable", StringComparison.OrdinalIgnoreCase);

    private static string ClassifyAvailability(params string?[] values)
    {
        int availableCount = values.Count(value => !string.IsNullOrWhiteSpace(value) &&
            !string.Equals(value, NotAvailable, StringComparison.OrdinalIgnoreCase));

        return availableCount switch
        {
            0 => NotAvailable,
            _ when availableCount == values.Length => "Ready",
            _ => "Partial"
        };
    }

    private static HpDiagnosticDashboardStatus GetStatus(string value)
    {
        if (value.StartsWith("Ready", StringComparison.OrdinalIgnoreCase) ||
            value.StartsWith("Succeeded", StringComparison.OrdinalIgnoreCase) ||
            value.StartsWith("Enabled", StringComparison.OrdinalIgnoreCase) ||
            value.StartsWith("Declared", StringComparison.OrdinalIgnoreCase))
        {
            return HpDiagnosticDashboardStatus.Ready;
        }

        if (value.StartsWith("Blocked", StringComparison.OrdinalIgnoreCase) ||
            value.StartsWith("NO-GO", StringComparison.OrdinalIgnoreCase) ||
            value.StartsWith("False -", StringComparison.OrdinalIgnoreCase) ||
            value.StartsWith("False - blocked", StringComparison.OrdinalIgnoreCase) ||
            value.StartsWith("False - not satisfied", StringComparison.OrdinalIgnoreCase) ||
            value.StartsWith("Missing", StringComparison.OrdinalIgnoreCase) ||
            value.StartsWith("Inconclusive", StringComparison.OrdinalIgnoreCase) ||
            value.StartsWith("Raw-only", StringComparison.OrdinalIgnoreCase) ||
            value.StartsWith("Partial", StringComparison.OrdinalIgnoreCase) ||
            value.StartsWith("Unknown", StringComparison.OrdinalIgnoreCase) ||
            value.StartsWith("Cached report contains optimistic", StringComparison.OrdinalIgnoreCase) ||
            value.StartsWith("Unset", StringComparison.OrdinalIgnoreCase) ||
            value.StartsWith("Not selected", StringComparison.OrdinalIgnoreCase))
        {
            return HpDiagnosticDashboardStatus.Blocked;
        }

        if (value.StartsWith("FourByte", StringComparison.OrdinalIgnoreCase) ||
            value.StartsWith("True - observed", StringComparison.OrdinalIgnoreCase) ||
            value.StartsWith("True - four-byte", StringComparison.OrdinalIgnoreCase))
        {
            return HpDiagnosticDashboardStatus.Warning;
        }

        return HpDiagnosticDashboardStatus.Normal;
    }
}
