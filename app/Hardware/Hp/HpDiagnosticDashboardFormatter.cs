namespace GHelper.Hardware.Hp;

public static class HpDiagnosticDashboardFormatter
{
    public const string NotAvailable = "Not available";
    public const string LegacyReportSchema = "Legacy / unknown";
    public const string RawFanLevelWarning = "Raw values are not RPM or percent.";
    public const string FanControlStatus = "Blocked - " + HpDiagnosticStatusText.FanControlNotImplemented;
    public const string SetFanMaxStatus = HpDiagnosticStatusText.SetFanMaxNoGo;
    public const string SetFanMaxReadinessStatus = "NO-GO";
    public const string SetFanMaxFirstWriteGateNotSatisfied = "False - not satisfied";
    public const string SetFanMaxFirstWriteGateMissingOldReportReason = "Missing first-write gate field(s) in cached/old report; failing closed to NO-GO until exact-device proof is present.";
    public const string SetFanMaxFirstWriteGateUnexpectedReportReason = "Cached report contains optimistic first-write gate data; failing closed to NO-GO.";
    public const string SetFanMaxInputLengthUnset = "Unset / not validated";
    public const string SetFanMaxPayloadLengthNotSelected = "Not selected";
    public const string SetFanMaxEvidenceMissing = "Missing / not proven";
    public const string SetFanMaxExperimentalPayloadUnknown = "Unknown / not selected";
    public const string SetFanMaxPhysicalResponseUnknown = "Unknown - missing or unrecognized experimental evidence";
    public const string SetFanMaxReadbackNotReliable = "False - FanMaxGet is not a reliable sole success criterion";
    public const string SetFanMaxDeveloperExperimentAllowed = "True - four-byte controlled developer experiments only";
    public const string SetFanMaxDeveloperExperimentPayload = "FourByte - developer experiment only";
    public const string SetFanMaxDeveloperExperimentNotAllowed = "False - developer experiment allowance is missing or invalid";
    public const string SetFanMaxDeveloperExperimentPayloadUnknown = "Unknown - developer experiment payload is missing or invalid";
    public const string SetFanMaxNormalControlNotValidated = "False - normal control is not validated";
    public const string SetFanMaxUserFacingControlNotAllowed = "False - user-facing control is not allowed";
    public const string PulseHistoryNotAvailable = "No pulse history available";
    public const string PulseHistoryNormalControlDisabled = "Disabled - normal fan control remains NO-GO";
    public const string SetFanLevelStatus = "NO-GO - non-executable research only";
    public const string SetFanLevelDryRunStatus = "Hardware/WMI-inert; serialization evidence only";
    public const string NoDiagnosticHardwareActions = "No HP BIOS or fan-write action is exposed in Diagnostic.";

    public static HpDiagnosticDashboardHealthSummary BuildHealthSummary(HpDiagnosticDashboardInput input)
    {
        return new HpDiagnosticDashboardHealthSummary(
            input.IsHpVictusDetected == true ? "Ready" : NotAvailable,
            ClassifyAvailability(
                input.RootWmiReadiness,
                input.HpqBIntMReadiness,
                input.HpqBDataInReadiness),
            ClassifyAvailability(input.SystemDesignDataDecodeStatus, input.SoftwareFanControlSupport),
            ClassifyAvailability(input.FanCount, input.MaxFanState, input.Fan1RawLevel, input.Fan2RawLevel),
            SetFanMaxStatus);
    }

    public static string FormatHealthSummary(HpDiagnosticDashboardHealthSummary summary)
    {
        return "Health: Device " + summary.DeviceStatus +
            " | WMI " + summary.WmiStatus +
            " | Telemetry " + summary.ReadOnlyTelemetryStatus +
            " | Fan read-only " + summary.FanReadOnlyStatus +
            " | Fan control " + summary.FanControlStatus;
    }

